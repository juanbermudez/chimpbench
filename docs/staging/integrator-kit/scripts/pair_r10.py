#!/usr/bin/env python3
"""Stage R10: the animals a kernel drove in one run of scripts/r10-night.ts, beside the same animals in a rules run of
the same world and days. Reads the per-animal-day row files of both runs (rows/*.jsonl[.gz]) and prints a markdown table:
the mean per animal-day in each run and the paired difference with a 95% t interval over animals. Standard library only.

  /usr/bin/python3 docs/staging/integrator-kit/scripts/pair_r10.py <kernel run folder> <rules run folder> [--md out.md]

A level comparison on one seed: the two runs are different worlds after the first day, so this is description, not a
registered result (docs/staging/r10-prereg.md section 8)."""
import glob, gzip, json, statistics, sys

MEASURES = [
    ('kcalFormula', 'energy eaten, kcal (the field\'s intake measure)', 0),
    ('kcalOut', 'energy out, kcal', 0),
    ('reservePct', 'reserves, % of the usual store a day', 2),
    ('km', 'distance, km (ground path)', 2),
    ('trips', 'trips to food begun', 1),
    ('tripsDone', 'trips to food completed', 2),
    ('actChanges', 'act changes', 1),
    ('drinks', 'drinks', 2),
    ('nestShare', 'share of the dark hours in a nest', 3),
]

def rows(folder):
    out = []
    for f in sorted(glob.glob(folder.rstrip('/') + '/rows/*')):
        op = gzip.open if f.endswith('.gz') else open
        with op(f, 'rt') as h:
            out += [json.loads(l) for l in h if l.strip()]
    return out

def t95(df):  # two-sided 95% quantile of Student's t (Cornish-Fisher expansion; exact to 3 decimals from df 5)
    z = 1.959964
    return z + (z ** 3 + z) / (4 * df) + (5 * z ** 5 + 16 * z ** 3 + 3 * z) / (96 * df ** 2) + (3 * z ** 7 + 19 * z ** 5 + 17 * z ** 3 - 15 * z) / (384 * df ** 3)

def per_animal(rs, key, ids):
    by = {}
    for r in rs:
        v = r.get(key)
        if r['id'] in ids and r.get('alive', True) and isinstance(v, (int, float)):
            by.setdefault(r['id'], []).append(v)
    return {k: sum(v) / len(v) for k, v in by.items()}

def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    md = sys.argv[sys.argv.index('--md') + 1] if '--md' in sys.argv else None
    if md in args: args.remove(md)
    if len(args) != 2: sys.exit(__doc__)
    kernel, rules = rows(args[0]), rows(args[1])
    ids = {r['id'] for r in kernel if r.get('driven')}
    days = sorted({r['day'] for r in kernel})
    lines = [f'# Stage R10: the {len(ids)} animals on the kernel beside the same animals on the rules (generated by docs/staging/integrator-kit/scripts/pair_r10.py; do not edit)', '',
             f'Kernel run `{args[0]}`, rules run `{args[1]}`; {len(days)} simulated days. Per animal and day; the difference is the kernel run minus the rules run on the same animal, with a 95% t interval over animals. One seed, and the two runs are different worlds after the first decision: a level comparison, not a registered result.', '',
             '| Measure | on the kernel | on the rules | difference | animals |', '|---|---|---|---|---|']
    for key, label, nd in MEASURES:
        a, b = per_animal(kernel, key, ids), per_animal(rules, key, ids)
        both = sorted(i for i in a if i in b)
        if len(both) < 3: continue
        d = [a[i] - b[i] for i in both]
        m, se = sum(d) / len(d), statistics.stdev(d) / len(d) ** 0.5
        h = t95(len(d) - 1) * se
        fmt = lambda x, sign=False: (f'{x:+,.{nd}f}' if sign else f'{x:,.{nd}f}')
        lines.append(f'| {label} | {fmt(sum(a[i] for i in both) / len(both))} | {fmt(sum(b[i] for i in both) / len(both))} | {fmt(m, True)} ({fmt(m - h, True)} to {fmt(m + h, True)}) | {len(both)} |')
    text = '\n'.join(lines) + '\n'
    if md: open(md, 'w').write(text)
    print(text)

if __name__ == '__main__':
    main()
